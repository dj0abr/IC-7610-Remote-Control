export let language = 'de';
export let locale = 'de-DE';

export function translate(source, values) {
  if (!source) return '';
  const catalog = language === 'en' ? english : german;
  const message = Object.hasOwn(catalog, source) ? catalog[source] : source;
  if (values) {
    return message.replace(/\{(\w+)\}/g, (placeholder, key) => values[key] ?? placeholder);
  }
  if (message !== source) return message;
  for (const [pattern, template] of templates) {
    const fields = pattern.exec(source)?.groups;
    if (fields) {
      for (const key of ['reason', 'setting', 'operation']) {
        if (fields[key]) fields[key] = translate(fields[key]);
      }
      return translate(template, fields);
    }
  }
  return source;
}

const labels = Array.from(document.querySelectorAll('[data-i18n]')).flatMap(node =>
  (node.dataset.i18n || 'textContent').split(' ').map(property =>
    [node, property, property === 'textContent' ? node.textContent : node.getAttribute(property)]));
const messages = new Map();

export function setMessage(node, source, property = 'textContent') {
  if (source) messages.set(node, [source, property]);
  else messages.delete(node);
  node[property] = translate(source);
}

export function setLanguage(next) {
  language = next === 'en' ? 'en' : 'de';
  locale = language === 'en' ? 'en-GB' : 'de-DE';
  document.documentElement.lang = language;
  for (const [node, property, source] of labels) {
    if (property === 'textContent') node.textContent = translate(source);
    else node.setAttribute(property, translate(source));
  }
  for (const [node, [source, property]] of messages) node[property] = translate(source);
}
